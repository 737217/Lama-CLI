# Английское множественное число — вторая форма. Для русского «дней» отдельный ключ,
# потому что три формы не укладываются в одну английскую пару.
_RU_MANY: dict[str, str] = {
    "{n} days ago": "{n} дней назад",
    "{n} weeks ago": "{n} недель назад",
}


def get_language() -> str:
    return _language


def set_language(lang: str) -> None:
    global _language
    if lang not in LANGS:
        raise ValueError(lang)
    _language = lang


def t(message: str, /, **values: object) -> str:
    """Перевести английский шаблон. Без перевода остаётся английский текст."""
    if _language == "ru":
        template = _RU.get(message, _RU_MANY.get(message, message))
    else:
        template = message
    if not values:
        return template
    return template.format(**values)


def tn(count: int, *, en: tuple[str, str], ru: tuple[str, str, str]) -> str:
    """Форма с числом: английские единственное и множественное, русские один/несколько/много."""
    n = abs(count)
    if _language == "ru":
        template = _ru_form(n, ru)
    else:
        template = en[0] if n == 1 else en[1]
    return template.format(n=count)


def _ru_form(count: int, forms: tuple[str, str, str]) -> str:
    one, few, many = forms
    mod10 = count % 10
    mod100 = count % 100
    if mod10 == 1 and mod100 != 11:
        return _RU.get(one, one)
    if mod10 in {2, 3, 4} and mod100 not in {12, 13, 14}:
        return _RU.get(few, few)
    return _RU_MANY.get(many, _RU.get(many, many))
